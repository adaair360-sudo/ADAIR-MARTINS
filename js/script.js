const root = document.documentElement;
const year = document.getElementById("year");
const toast = document.getElementById("toast");
const nav = document.getElementById("nav");
const menuBtn = document.getElementById("menuBtn");
const themeBtn = document.getElementById("themeBtn");
const langBtn = document.getElementById("langBtn");
const langLabel = document.getElementById("langLabel");
const printBtn = document.getElementById("printBtn");
const copyEmail = document.getElementById("copyEmail");

const storedTheme = localStorage.getItem("cv-theme");
const storedLang = localStorage.getItem("cv-lang") || "pt";
const preferredDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
const theme = storedTheme || (preferredDark ? "dark" : "light");

function applyTheme(next) {
  root.setAttribute("data-theme", next);
  localStorage.setItem("cv-theme", next);
  themeBtn.setAttribute("aria-label", next === "dark" ? "Ativar tema claro" : "Ativar tema escuro");
}

function applyLang(next) {
  const dict = i18n[next];
  document.documentElement.lang = next === "pt" ? "pt-BR" : "en";
  document.documentElement.setAttribute("translate", "no");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (dict[key]) el.title = dict[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    if (dict[key]) el.setAttribute("aria-label", dict[key]);
  });
  langLabel.textContent = next === "pt" ? "EN" : "PT";
  localStorage.setItem("cv-lang", next);
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("is-on");
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => toast.classList.remove("is-on"), 2800);
}

async function copyText(text) {
  if (navigator.clipboard && window.isSecureContext) {
    await navigator.clipboard.writeText(text);
    return;
  }

  const input = document.createElement("textarea");
  input.value = text;
  input.setAttribute("readonly", "");
  input.style.position = "fixed";
  input.style.left = "-9999px";
  document.body.appendChild(input);
  input.select();
  const ok = document.execCommand("copy");
  input.remove();
  if (!ok) throw new Error("copy failed");
}

year.textContent = String(new Date().getFullYear());
applyTheme(theme);
applyLang(storedLang);

themeBtn.addEventListener("click", () => {
  const next = root.getAttribute("data-theme") === "dark" ? "light" : "dark";
  applyTheme(next);
});

langBtn.addEventListener("click", () => {
  const next = localStorage.getItem("cv-lang") === "en" ? "pt" : "en";
  applyLang(next);
});

printBtn.addEventListener("click", () => window.print());

menuBtn.addEventListener("click", () => {
  const open = nav.classList.toggle("is-open");
  menuBtn.setAttribute("aria-expanded", String(open));
});

document.addEventListener("click", (event) => {
  if (!nav.classList.contains("is-open")) return;
  if (nav.contains(event.target) || menuBtn.contains(event.target)) return;
  nav.classList.remove("is-open");
  menuBtn.setAttribute("aria-expanded", "false");
});

nav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    nav.classList.remove("is-open");
    menuBtn.setAttribute("aria-expanded", "false");
  });
});

copyEmail.addEventListener("click", async () => {
  const email = copyEmail.dataset.email;
  const lang = localStorage.getItem("cv-lang") || "pt";
  try {
    await copyText(email);
    showToast(i18n[lang].copied);
  } catch {
    showToast(i18n[lang].copyFail);
  }
});

const sections = [...document.querySelectorAll("section[id]")];
const navLinks = [...nav.querySelectorAll("a")];

const spy = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      navLinks.forEach((link) => {
        link.classList.toggle("is-active", link.getAttribute("href") === `#${entry.target.id}`);
      });
    });
  },
  { rootMargin: "-40% 0px -50% 0px", threshold: 0 }
);

sections.forEach((section) => spy.observe(section));

const skillObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      const level = entry.target.dataset.level;
      entry.target.style.setProperty("--level", `${level}%`);
      entry.target.classList.add("is-on");
      skillObserver.unobserve(entry.target);
    });
  },
  { threshold: 0.4 }
);

document.querySelectorAll(".skill").forEach((skill) => {
  skill.style.setProperty("--level", `${skill.dataset.level}%`);
  skillObserver.observe(skill);
});
